import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { randomUUID } from 'node:crypto';
import { startHarness } from './helpers/harness.js';
import { seedTagCatalog } from './helpers/tag-catalog.js';
import { DEFAULT_TAG, SHA, TOKEN } from './helpers/gitlab-fixture.js';

const h = await startHarness(1, 'memory://', { localManagement:true, analytics:{ environment:'test', siteInstanceId:'browser-fixture' } });
const seeded = [];
for (let index = 1; index <= 8; index++) seeded.push(await seedTagCatalog(h.db, h.config.audience, ['文档处理'], index));
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL as any } : {}) });
const context = await browser.newContext({ viewport:{ width:1280, height:720 } });
const page = await context.newPage();
await page.addInitScript("Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => {} }, configurable: true })");
const errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.url().includes('/api/analytics/events') && !response.ok()) errors.push(`analytics HTTP ${response.status()}`); });
try {
  await page.goto(h.origin);
  await page.getByTestId('app-card').first().waitFor();
  const read = async () => (await h.db.query<any>('SELECT event_name,app_id,snapshot_id,result_set_id,flow_id,publication_id,attributes FROM analytics_events ORDER BY received_at')).rows;
  for (let attempt=0; attempt<30 && !(await read()).some(row => row.event_name === 'app_card_exposed'); attempt++) await page.waitForTimeout(200);
  let rows = await read();
  assert.ok(rows.some(row => row.event_name === 'portal_viewed'));
  assert.ok(rows.some(row => row.event_name === 'catalog_results_viewed' && row.attributes.trigger === 'initial'));
  assert.ok(rows.some(row => row.event_name === 'app_card_exposed'), `visible cards counted after one second: ${JSON.stringify({ names: rows.map(row => row.event_name), errors })}`);
  assert.ok(rows.filter(row => row.event_name === 'app_card_exposed').every(row => row.snapshot_id && row.result_set_id));
  const directRandom = await context.newPage();
  await directRandom.goto(`${h.origin}/?discover=random`);
  await directRandom.getByTestId('wheel-current').waitFor();
  for (let attempt=0; attempt<30 && !(await read()).some(row => row.event_name === 'app_card_exposed' && row.attributes.section === 'random'); attempt++) await directRandom.waitForTimeout(200);
  const directRows = await read();
  assert.ok(directRows.some(row => row.event_name === 'portal_viewed' && row.attributes.pageContext === 'random'), 'a direct wheel link initializes analytics from the server switch');
  assert.ok(directRows.some(row => row.event_name === 'app_card_exposed' && row.attributes.section === 'random'), 'a direct wheel link records visible card exposure');
  await directRandom.close();
  let randomRequests = 0;
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/apps/random') randomRequests++; });
  await page.getByTestId('tab-random').click();
  await page.getByTestId('wheel-current').waitFor();
  for (let attempt=0; attempt<30 && !(await read()).some(row => row.event_name === 'app_card_exposed' && row.attributes.section === 'random'); attempt++) await page.waitForTimeout(200);
  assert.ok((await read()).some(row => row.event_name === 'app_card_exposed' && row.attributes.section === 'random'));
  await page.getByRole('button', { name:'下一个应用', exact:true }).click();
  const previousWheelApp = await page.getByTestId('wheel-current').getByTestId('app-card').getAttribute('data-app-id');
  await page.getByTestId('catalog-wheel').hover();
  await page.mouse.wheel(0, 110);
  await page.waitForFunction(id => document.querySelector('[data-testid="wheel-current"] [data-app-id]')?.getAttribute('data-app-id') !== id, previousWheelApp);
  assert.equal(randomRequests,1, 'rotating the wheel does not sample again');
  await page.getByTestId('tab-catalog').click();
  await page.getByTestId('share-button').click();
  await page.getByTestId('copy-publish-prompt').waitFor();
  await page.getByTestId('copy-publish-prompt').click();
  await page.keyboard.press('Escape');
  await page.getByRole('textbox', { name:'搜索应用名称、用途或能力' }).fill('application');
  await page.getByTestId('search-button').click();
  await page.waitForFunction(() => document.querySelector('.catalog-results')?.getAttribute('aria-busy') === 'false');
  await page.getByTestId('app-card').first().locator('.app-title').click();
  await page.getByTestId('app-detail').waitFor();
  await page.getByTestId('use-agent').first().click();
  await page.getByTestId('copy-agent-prompt').waitFor();
  await page.getByTestId('copy-agent-prompt').click();
  await page.waitForTimeout(700);
  await page.evaluate("Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => { throw new Error('fixture failure') } }, configurable: true }); document.execCommand = () => false");
  await page.getByTestId('copy-agent-prompt').click();
  await page.getByTestId('copy-agent-prompt').waitFor();
  await page.waitForTimeout(700);
  rows = await read();
  assert.ok(rows.some(row => row.event_name === 'catalog_results_viewed' && row.attributes.trigger === 'search' && row.attributes.hasQuery));
  assert.ok(rows.some(row => row.event_name === 'app_detail_viewed'));
  assert.ok(rows.some(row => row.event_name === 'app_entry_clicked' && row.attributes.entryKind === 'agent'));
  assert.ok(rows.some(row => row.event_name === 'prompt_copy_result' && row.attributes.promptPurpose === 'usage' && row.attributes.result === 'success'));
  assert.ok(rows.some(row => row.event_name === 'prompt_copy_result' && row.attributes.promptPurpose === 'usage' && row.attributes.result === 'failure'), 'failed copy is not reported as success');
  const panel = rows.find(row => row.event_name === 'publish_panel_viewed');
  const publishCopy = rows.find(row => row.event_name === 'prompt_copy_result' && row.attributes.promptPurpose === 'publish');
  assert.ok(panel?.flow_id && panel.flow_id === publishCopy?.flow_id, 'one opened panel uses the same non-authorizing flow id');
  assert.ok(!JSON.stringify(rows).includes('application'), 'raw search text is not recorded');
  assert.deepEqual(errors, []);
  const draft = await h.service.submit({ projectId:1, appKey:'sample-1', manifestPath:'ai-app.json', commitSha:SHA, tag:DEFAULT_TAG }, TOKEN, randomUUID());
  assert.equal(draft.status, 'preview_ready');
  const preview = await context.newPage();
  await preview.goto(draft.previewUrl);
  await preview.getByTestId('confirm-publication').waitFor();
  for (let attempt=0; attempt<20 && !(await read()).some(row => row.event_name === 'publication_preview_viewed'); attempt++) await page.waitForTimeout(100);
  const previews = (await read()).filter(row => row.event_name === 'publication_preview_viewed');
  assert.equal(previews.length, 1);
  assert.equal(previews[0].publication_id, draft.id);
  assert.equal(previews[0].attributes.viewerContext, 'publication_link');
  await preview.getByTestId('tab-catalog').click();
  await preview.getByTestId('app-card').first().waitFor();
  assert.equal(new URL(preview.url()).hash.includes('publish'), false, 'leaving a publication preview clears its publish fragment');
  const management = await context.newPage();
  await management.goto(`${h.origin}/admin#publish=${draft.id}`);
  await management.getByTestId('confirm-publication').waitFor();
  for (let attempt=0; attempt<20 && !(await read()).some(row => row.event_name === 'publication_preview_viewed' && row.attributes.viewerContext === 'management'); attempt++) await page.waitForTimeout(100);
  assert.ok((await read()).some(row => row.event_name === 'publication_preview_viewed' && row.publication_id === draft.id && row.attributes.viewerContext === 'management'), 'management preview has its own context');
  await page.route('**/api/analytics/events', route => route.abort());
  await page.goto(h.origin);
  await page.getByRole('textbox', { name:'搜索应用名称、用途或能力' }).fill('application');
  await page.getByTestId('search-button').click();
  await page.getByTestId('app-card').first().waitFor();
  await page.getByTestId('app-card').first().locator('.app-title').click();
  await page.getByTestId('app-detail').waitFor();
  console.log(JSON.stringify({ status:'PASS', events:[...new Set(rows.map(row => row.event_name))], boundary:'local fixture; no production or external writes' }));
} finally { await browser.close(); await h.close(); }
