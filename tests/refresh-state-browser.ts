import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { startIdentityHarness } from './helpers/identity-fixture.js';
import { seedTagCatalog } from './helpers/tag-catalog.js';
import { DEFAULT_TAG, SHA, TOKEN } from './helpers/gitlab-fixture.js';

const h = await startIdentityHarness('/plaza');
const owner = await h.login('fixture-admin');
for (let index = 1; index <= 8; index++) await seedTagCatalog(h.db, h.config.audience, ['焦点核验'], index);
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL as any } : {}) });
const context = await browser.newContext();
const [name, value] = owner.cookie.split('=');
await context.addCookies([{ name, value, url: `${h.origin}/plaza/` }]);
await context.addInitScript(() => localStorage.setItem('fixture-sky-token', 'fixture-admin'));
const page = await context.newPage();
const errors: string[] = [];
let exchanges = 0, randomRequests = 0;
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => {
  const path = new URL(request.url()).pathname;
  if (path.endsWith('/api/auth/tiangong/exchange')) exchanges++;
  if (path.endsWith('/api/apps/random')) randomRequests++;
});
const wheel = page.getByTestId('catalog-wheel');
const batch = () => wheel.getByTestId('app-card').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-app-id')));
const currentId = () => page.getByTestId('wheel-current').getByTestId('app-card').getAttribute('data-app-id');
const ready = () => page.waitForFunction(() => { const button = document.querySelector<HTMLButtonElement>('[data-testid="random-refresh"]'); return button && !button.disabled; });
try {
  for (const failure of ['503', 'network', 'status']) {
    const path = failure === 'status' ? '**/api/auth/tiangong/status' : '**/api/auth/me';
    await page.route(path, route => failure === 'network' ? route.abort('failed') : route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'IDENTITY_UNAVAILABLE', message: '初始化核验暂不可用' } }) }));
    await page.goto(`${h.origin}/plaza/`);
    await page.getByRole('button', { name: '重试身份核验', exact: true }).waitFor();
    await page.unroute(path);
    await page.getByRole('button', { name: '重试身份核验', exact: true }).click();
    await page.getByRole('button', { name: '退出广场', exact: true }).waitFor();
  }
  assert.equal(exchanges, 0, 'manual retry recovers the valid session without another exchange');
  await page.getByTestId('tab-random').click();
  await page.getByTestId('wheel-current').waitFor();
  await page.getByRole('button', { name: '下一个应用', exact: true }).click();
  const before = await batch(), active = await currentId();
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  const appRoute = `**/api/apps/${active}`;
  await page.route(appRoute, async route => { await gate; await route.continue(); });
  const entered = page.waitForRequest(appRoute);
  await page.evaluate(() => dispatchEvent(new Event('focus')));
  await entered;
  await page.getByTestId('random-refresh').filter({ hasText: '正在核验…' }).waitFor();
  assert.deepEqual(await batch(), before);
  assert.equal(await currentId(), active);
  await page.getByRole('button', { name: '下一个应用', exact: true }).click();
  const focusedActive = await currentId();
  release(); await ready();
  await page.unroute(appRoute);
  assert.deepEqual(await batch(), before);
  assert.equal(await currentId(), focusedActive, 'navigation during revalidation is retained');
  assert.equal(randomRequests, 1, 'focus does not sample a new batch');
  await page.route(appRoute, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'SERVICE_UNAVAILABLE', message: '批次核验暂不可用' } }) }));
  await page.evaluate(() => dispatchEvent(new Event('focus')));
  await page.getByRole('alert').filter({ hasText: '批次核验暂不可用' }).waitFor();
  assert.deepEqual(await batch(), before);
  assert.equal(await currentId(), focusedActive);
  await page.unroute(appRoute);
  await page.route(appRoute, route => route.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ error: { code: 'APP_NOT_FOUND', message: '应用已不可访问' } }) }));
  const revoked = page.waitForResponse(appRoute);
  await page.evaluate(() => dispatchEvent(new Event('focus')));
  await revoked; await ready();
  assert.deepEqual(await batch(), before.filter(id => id !== active), 'revoked item is removed without sampling replacements');
  assert.equal(randomRequests, 1);
  await page.unroute(appRoute);
  await page.getByTestId('random-refresh').click(); await ready();
  assert.equal(randomRequests, 2, 'the user can explicitly request a new batch');
  const forbiddenRoute = `**/api/apps/${await currentId()}`;
  await page.route(forbiddenRoute, route => route.fulfill({ status: 403, contentType: 'application/json', body: JSON.stringify({ error: { code: 'APP_ACTION_DENIED', message: '批次访问已失效' } }) }));
  await page.evaluate(() => dispatchEvent(new Event('focus')));
  await page.getByRole('alert').filter({ hasText: '批次访问已失效' }).waitFor();
  assert.equal(await wheel.count(), 0);
  await page.unroute(forbiddenRoute);

  const publication = await h.service.submit({ projectId: 1, appKey: 'sample-1', manifestPath: 'ai-app.json', commitSha: SHA, tag: DEFAULT_TAG }, TOKEN, crypto.randomUUID());
  await page.goto(publication.previewUrl);
  await page.getByTestId('confirm-publication').waitFor();
  await page.waitForFunction(() => !document.querySelector<HTMLButtonElement>('[data-testid="confirm-publication"]')?.disabled);
  const preview = page.locator('.publication-preview'), previewText = await preview.innerText();
  const publicationRoute = `**/api/publications/${publication.id}`;
  let releasePublication!: () => void;
  const publicationGate = new Promise<void>(resolve => { releasePublication = resolve; });
  await page.route(publicationRoute, async route => { await publicationGate; await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'SERVICE_UNAVAILABLE', message: '发布状态暂不可用' } }) }); });
  const publicationEntered = page.waitForRequest(publicationRoute);
  await page.evaluate(() => dispatchEvent(new Event('focus')));
  await publicationEntered;
  await page.getByText('正在更新发布状态…', { exact: true }).waitFor();
  assert.equal(await preview.innerText(), previewText);
  assert.equal(await page.getByTestId('confirm-publication').isDisabled(), true);
  releasePublication();
  await page.getByRole('alert').filter({ hasText: '发布状态暂不可用' }).waitFor();
  assert.equal(await preview.innerText(), previewText);
  await page.unroute(publicationRoute);
  await page.getByRole('button', { name: '重新读取状态', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector<HTMLButtonElement>('[data-testid="confirm-publication"]')?.disabled);
  await page.route(publicationRoute, route => route.fulfill({ status: 403, contentType: 'application/json', body: JSON.stringify({ error: { code: 'APP_ACTION_DENIED', message: '发布授权已失效' } }) }));
  await page.evaluate(() => dispatchEvent(new Event('focus')));
  await page.getByRole('alert').filter({ hasText: '发布授权已失效' }).waitFor();
  assert.equal(await preview.count(), 0, 'confirmed access loss clears the old publication');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'PASS', cases: ['initial identity retries', 'wheel batch and index preserved', 'wheel 404/403', 'publication refresh and access loss'], boundary: 'loopback fixtures only' }));
} finally { await browser.close(); await h.close(); }
